import { Tool } from '../ports/tool.interface';
import { AgentMessage } from '../ports/agent-types';

export interface ToolCallHistoryEntry {
  tool: string;
  argsHash: string;
}

export interface AgentExecutionState {
  history: ToolCallHistoryEntry[];
  warningInjected: boolean;
  turnsSinceWarning: number;
}

/**
 * All mutable state that belongs to a single `run()` invocation.
 *
 * Created fresh at the start of every `run()` call so concurrent invocations
 * on the same singleton executor never share state with each other.
 *
 * Immutable fields (runId, runStart, model …) are `readonly` to make it clear
 * they do not change over the lifetime of the run. Mutable fields (turns,
 * localMessages, executionState) change as the agent progresses through turns.
 */
export interface AgentRunContext {
  readonly runId: string;
  readonly agentName: string;
  /** Timestamp (Date.now()) captured when run() was first called. */
  readonly runStart: number;
  readonly model: string;
  readonly maxTurns: number;
  readonly systemPrompt: string;
  readonly tools: Tool[];
  /** Grows as the agent and user exchange messages within one run. */
  localMessages: AgentMessage[];
  /** Incremented at the top of every turn iteration. */
  turns: number;
  /** Sliding-window loop-detection state, reset per run. */
  executionState: AgentExecutionState;
  /** Total input tokens consumed by LLM calls during this run. */
  totalInputTokens: number;
  /** Total output tokens generated by LLM calls during this run. */
  totalOutputTokens: number;
  /** Number of LLM turns that included a thought/reasoning phase. */
  totalThoughtTurns: number;
}
